"""Regenerate franco/idn_tlds.py from the IANA root zone.

    python scripts/idn_tlds.py

Only the non-ASCII (xn--) TLDs are kept, decoded to the script a draft
would be written in. ASCII TLDs aren't listed: any ASCII label after a dot
already counts as a link.
"""

import sys
import urllib.request
from pathlib import Path

SOURCE = "https://data.iana.org/TLD/tlds-alpha-by-domain.txt"
TARGET = Path(__file__).resolve().parent.parent / "franco" / "idn_tlds.py"


def render(lines: list[str]) -> str:
    version = lines[0].lstrip("# ").strip()
    tlds = sorted(
        line.strip().lower().encode("ascii").decode("idna")
        for line in lines[1:]
        if line.strip().lower().startswith("xn--")
    )
    body = "".join(f"    {t!r},\n" for t in tlds)
    return (
        '"""Non-ASCII top-level domains in the IANA root zone.\n\n'
        "Generated by scripts/idn_tlds.py; don't edit by hand.\n"
        f"Source: {SOURCE}\n"
        f"{version}\n"
        '"""\n\n'
        f"IDN_TLDS = frozenset({{\n{body}}})\n"
    )


def main() -> int:
    with urllib.request.urlopen(SOURCE, timeout=30) as resp:
        lines = resp.read().decode("ascii").splitlines()
    TARGET.write_text(render(lines), encoding="utf-8")
    print(f"wrote {TARGET}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
